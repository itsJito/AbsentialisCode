# Writes docs/audio/weapon_asset_manifest.md from assets/audio/index.json (produced by `gradlew prepareAudio`)
# and src/main/resources/content/weapon_audio.json. Run from the project root:  python tools/audio/make_manifest.py
# Every figure in the tables is measured by the pipeline; nothing here is typed in by hand except the source
# descriptions at the top, which are copied from the pages the files were downloaded from.
import io, json, re

index = json.load(io.open('assets/audio/index.json', encoding='utf-8'))
profiles = json.load(io.open('src/main/resources/content/weapon_audio.json', encoding='utf-8'))
items = io.open('src/main/resources/content/items.json', encoding='utf-8').read()

def item(wid):
    m = re.search(r'\{"id": "%s", "name": "([^"]+)".*?"weapon": \{"family": "([^"]+)", "caliber": "([^"]+)".*?"modes": \[([^\]]*)\], "rpm": (\d+)' % re.escape(wid), items, re.S)
    return m.groups() if m else ('?', '?', '?', '?', '?')

MATCH = {
    'exact': 'the same firearm type and cartridge',
    'exact-type': 'the same class of firearm and action',
    'close': 'the same class and a comparable cartridge',
    'substitute': 'substitution: no recording of this class exists in the library; nearest available character',
}
out = []
w = out.append
w('# Weapon audio asset manifest - Absentialis 0.5')
w('')
w('Generated by `python tools/audio/make_manifest.py` from `assets/audio/index.json` (written by `gradlew prepareAudio`)')
w('on %s. Do not edit by hand: change `tools/audio/sources.json` or `content/weapon_audio.json` and regenerate.' % index['generated'])
w('')
w('## Sources')
w('')
w('All recordings were downloaded on 2026-10-10 and are stored unmodified under `tools/audio/originals/`.')
w('')
w('| Source | Author(s) as credited on the page | Licence | URL | Used for |')
w('|---|---|---|---|---|')
w('| The Free Firearm Sound Library ("Prepared SFX Library", 56 WAV, 96 kHz / 24-bit / stereo) | Ben Jaszczak, Brian Nelson, Kevin Heras, Matthew Nanney | CC0 1.0 (public domain) | https://opengameart.org/content/the-free-firearm-sound-library (file: https://opengameart.org/sites/default/files/Prepared%20SFX%20Library.7z) | every gunshot layer |')
w('| Gun Reload Sound Effects (clipload1, clipload2, singlebullet1) | BMacZero (Brian MacIntosh) | CC0 1.0 | https://opengameart.org/content/gun-reload-sound-effects | magazine and single-round handling |')
w('| Gun Reload Sounds (gunreload1, assaultriflereload1, shotguncock) | as credited on the page (not recorded when the files were fetched - see "Open items") | CC0 1.0 as stated on the page | https://opengameart.org/content/gun-reload-sounds | reload, bolt and pump handling |')
w('| Footsteps on different surfaces | congusbongus; per-surface derivations credited in each folder\'s `license.txt` (swuing, Eelke, Ali_6868, ceberation, EminYILDIRIM) | CC-BY 3.0 (gravel source CC0) | https://opengameart.org/content/footsteps-on-different-surfaces | footsteps |')
w('')
w('No audio from any commercial game, film or paid library is used, and none was downloaded. The games the brief')
w('names as a reference for the *result* were used as a description of the goal only.')
w('')
w('### What the firearm library is, and is not')
w('')
w('Its master sheet (`Prepared Master Sheet.csv`, shipped with the library) describes every file. Each firearm has a')
w('"near distance, front of shooter, left/right stereo" recording and a "mid distance, front of shooter, forward/back')
w('stereo" recording, each holding two or more single shots; the three automatic weapons also have burst recordings.')
w('')
w('- Perspectives available: **near** and **mid** only. There is no separate mechanical-only, interior, far-field or')
w('  suppressed recording of any weapon.')
w('- The near recordings reach digital full scale on most shots (see "flat-top samples" below): the muzzle blast')
w('  overloaded the converter for a fraction of a millisecond. Nothing in the pipeline hides this; it is what a')
w('  close microphone does, and the first millisecond of a gunshot is where it is least audible.')
w('- Burst recordings are **not** used. Every round the game fires is assembled from single-shot recordings and')
w('  scheduled by the engine, so automatic fire never plays a baked loop.')
w('')
w('## Game weapons and the recordings they use')
w('')
w('The game\'s weapons are fictional models; each is given the recordings of the real firearm closest to it. "Match"')
w('says honestly how close that is.')
w('')
w('| Game weapon | Class / calibre / modes / RPM | Recorded firearm | Match | Close takes | Distant takes | Action events after the shot |')
w('|---|---|---|---|---|---|---|')
for wid, p in profiles['weapons'].items():
    name, fam, cal, modes, rpm = item(wid)
    ix = index['weapons'].get(p['set'], {})
    act = profiles['actions'].get(p.get('action', ''), [])
    acts = ', '.join('%s at %d ms' % (a['sample'], round(a['at'] * 1000)) for a in act) or 'none (revolver: nothing cycles)'
    w('| %s (`%s`) | %s / %s / %s / %s | %s | %s | %d | %d%s | %s |' % (name, wid, fam, cal, modes.replace('"', ''), rpm, p['analogue'], MATCH.get(p['match'], p['match']),
        ix.get('takes', 0), ix.get('distant', 0), ' (derived)' if ix.get('distantDerived') else '', acts))
w('| Crossbow (`weapon.crossbow`) | special | none | not a firearm: keeps its synthesised string release | - | - | - |')
w('')
w('## Source files, as measured')
w('')
w('"Flat-top samples" counts frames in runs of three or more at digital full scale in either channel. "Directness" is the')
w('energy of the first 30 ms of each shot over the energy of the following second: high for a close microphone, low')
w('for one down the range.')
w('')
w('| Set | File | Library description | Rate / bits / channels | Length | Single shots found | Flat-top samples | Directness | Used as |')
w('|---|---|---|---|---|---|---|---|---|')
sheet = {}
try:
    import csv
    raw = io.open('tools/audio/originals/Prepared SFX Library/Prepared Master Sheet.csv', encoding='utf-8', errors='replace', newline='').read().replace('\r\n', '\n').replace('\r', '\n')
    for r in csv.reader(raw.split('\n')):
        if len(r) >= 6: sheet[r[0]] = r[5]
except Exception as e:
    print('master sheet not read:', e)
for sid, ix in index['weapons'].items():
    for s in ix['sources']:
        fn = s['file'].split('/')[-1]
        w('| `%s` | `%s` | %s | %d Hz / %d / %d | %.1f s | %d | %d | %.2f | %s |' % (sid, s['file'], sheet.get(fn, '(not in sheet)'), s['rate'], s['bits'], s['channels'], s['seconds'], s['shots'], s['clippedSamples'], s['directness'],
            'transient, body, tail' if s['use'] == 'close' else 'distant layer, reflection source'))
w('')
w('## Layers produced for each set (`assets/audio/weapons/<set>/`)')
w('')
w('| Layer | File pattern | Format | How it is made |')
w('|---|---|---|---|')
w('| Transient | `<set>_tr<n>.wav` | 44.1 kHz 16-bit mono | the take above the %d Hz crossover, first 60 ms whole, cosine fade to 100 ms; begins 1 ms before the onset, no fade-in |' % 1100)
w('| Body | `<set>_bd<n>.wav` | 11.025 kHz 16-bit mono | the take below the crossover (zero-phase low-pass), up to 2.6 s |')
w('| Tail | `<set>_tl<n>.wav` | 44.1 kHz 16-bit mono | what is left above the crossover after the transient window, up to 2.6 s |')
w('| Distant | `<set>_ds<n>.wav` | 11.025 kHz 16-bit mono | the mid-distance take, low-passed at 2.2 kHz |')
w('')
w('Transient + body + tail of one take sum back to that take (the split is complementary), so layering adds nothing')
w('that was not recorded and removes nothing that was. Processing applied: mono fold-down, peak alignment to 0.9 within')
w('a take, the crossover, cosine fades at the cut points, windowed-sinc sample-rate conversion, 1-LSB triangular dither.')
w('No pitch shifting, compression, EQ or reverb is baked into any file.')
w('')
w('## Handling sounds (`assets/audio/handling/`)')
w('')
w('| Name | Source file | Events cut |')
w('|---|---|---|')
for n, h in index['handling'].items():
    w('| `%s_<n>` | `%s` | %d (%s) |' % (n, h['source'], len(h['events']), ', '.join('%.2f s' % e['at'] for e in h['events'])))
w('')
w('## Footsteps (`assets/audio/footsteps/<surface>/`)')
w('')
w('| Surface | Steps | Source folder | Recorded or derived |')
w('|---|---|---|---|')
for n, f in index['footsteps'].items():
    w('| %s | %d | `%s` | %s |' % (n, f['count'], f['source'], 'derived (filtered / re-pitched / blended - see `tools/audio/sources.json`)' if f['derived'] else 'recorded'))
w('')
w('## Gaps, substitutions and open items')
w('')
w('- **Suppressed fire** has no recordings. It is rendered from the unsuppressed takes (transient and body reduced,')
w('  low-passed, slower, far less reverb, action noise raised - `suppressed` in `content/weapon_audio.json`). This is a')
w('  rendering, not a recording, and is the weakest part of the set.')
w('- **Semi-automatic shotguns** (Riot, Striker) use pump-action 12-gauge recordings; the report is right for the')
w('  cartridge, the action noise after it is assembled from generic handling sounds.')
w('- **Magnum handguns** (Desert Eagle, Killer9, Handcannon) have no magnum-pistol recording in the library and use')
w('  rifle-calibre recordings (.32 Winchester Special, .30-30, .30-06) played marginally faster or slower. They are loud')
w('  and distinct from each other, but they are substitutes.')
w('- **Punisher** uses a .22 pistol recording lowered in rate, **Matilda** a .380, **Tommy** a PPSh: substitutes of the')
w('  right class.')
w('- **Mechanical layers** are not recordings of the same firearms: the handling sources are generic (one of them')
w('  recorded with airsoft replicas, as its page states). They are mixed low for that reason.')
w('- **Takes per weapon**: most firearms have two near single shots in the library. The engine pairs the high band of')
w('  one take with the low band of another and varies rate and level per shot, but two takes is two takes.')
w('- **Asphalt and dirt footsteps** are derived from the concrete and grass recordings (table above).')
w('- **Attribution to confirm**: the author credit for "Gun Reload Sounds" was not written down when the files were')
w('  fetched. The page URL is above; the credit should be copied from it into `ATTRIBUTION.md` before any public release.')
w('- Not used from the library: Arisaka, Mossberg (bolt-action 12 gauge), Ruger Single Six, Savage 10, SKS, Tikka and all')
w('  burst files. They remain in `tools/audio/originals/` for future weapons.')
io.open('docs/audio/weapon_asset_manifest.md', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('manifest written:', len(out), 'lines')
