    private void glyphs() {
        for (String[] g : GLYPHS) {
            int h = g.length - 1, w = g[1].length();
            int[] r = alloc(g[0], w, h);
            for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
                char ch = x < g[y + 1].length() ? g[y + 1].charAt(x) : '.';
                int c = switch (ch) {
                    case '#' -> BONE; case '+' -> Tex.rgb(240, 236, 220); case '-' -> Tex.rgb(150, 144, 128); case 'o' -> INK;
                    case 'r' -> RED; case 'a' -> AMBER; case 'g' -> GREEN; default -> 0;
                };
                put(r, x, y, c);
            }
        }
        // drop shadow pass for glyphs (1px down-right, ink at 60%) so they read on any background
        for (String[] g : GLYPHS) {
            if (g[0].equals("crosshatch")) continue;
            int[] r = rects.get(g[0]);
            int[] copy = new int[r[2] * r[3]];
            for (int y = 0; y < r[3]; y++) for (int x = 0; x < r[2]; x++) copy[y * r[2] + x] = px[(r[1] + y) * SIZE + r[0] + x];
            for (int y = 0; y < r[3]; y++) for (int x = 0; x < r[2]; x++) {
                if (copy[y * r[2] + x] != 0) continue;
                boolean sh = x > 0 && y > 0 && copy[(y - 1) * r[2] + x - 1] != 0;
                if (sh) put(r, x, y, 0x99000000);
            }
        }
    }

    private void upload() {
        ByteBuffer b = MemoryUtil.memAlloc(SIZE * SIZE * 4);
        for (int c : px) b.put((byte) Tex.r(c)).put((byte) Tex.g(c)).put((byte) Tex.b(c)).put((byte) Tex.a(c));
        b.flip();
        tex = glGenTextures();
        glBindTexture(GL_TEXTURE_2D, tex);
        glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, SIZE, SIZE, 0, GL_RGBA, GL_UNSIGNED_BYTE, b);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, org.lwjgl.opengl.GL12.GL_CLAMP_TO_EDGE);
        glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, org.lwjgl.opengl.GL12.GL_CLAMP_TO_EDGE);
        MemoryUtil.memFree(b);
    }
