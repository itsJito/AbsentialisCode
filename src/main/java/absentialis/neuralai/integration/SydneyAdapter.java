package absentialis.neuralai.integration;

import absentialis.entity.Actor;
import absentialis.entity.Physics;
import absentialis.entity.Vital;
import absentialis.neuralai.api.SydneyBridge;
import absentialis.neuralai.api.Vec3;
import absentialis.neuralai.combat.MeleeSpec;
import absentialis.scene.Raid;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * The body side of the bridge, on the game's own character controller. NeuralAI states an intent; this turns it
 * into what the existing systems already know how to do - a walk along a navigation path, a stance, a facing, a
 * wound-up blow - and reports back honestly: RUNNING while it is happening, COMPLETED when the body is there,
 * BLOCKED when it has stopped making progress, INTERRUPTED when something knocked it out of it, FAILED when it was
 * asked for something this body cannot do.
 *
 * Motion is produced, never played back: the destination becomes a velocity through navigation and the voxel
 * controller, the pose is generated by the animator from how the body is actually moving, and a body under physics
 * (a stagger, a fall - the Sydney Engine proper) reports FOOTING_LOST and takes no intents until it is up again.
 * A blow is a wind-up, a contact window and a recovery; whether the window hits anything is the raid's ruling.
 */
public final class SydneyAdapter implements SydneyBridge {
    /** Sprint speed as a multiple of the archetype's run speed, the fastest anyone sprints, and how long the wind lasts and takes to come back (seconds). */
    public static float SPRINT_MUL = 1.38f, SPRINT_MAX = 6.4f, SPRINT_SECONDS = 9f, SPRINT_RECOVER = 14f;
    /** 1.3: above this speed (m/s) a body faces the way it is going, and its aim is a twist of the torso of at most TWIST radians from that. */
    public static float RUN_FACING = 2.4f, TWIST = 1.2f;

    private static final class Body {
        MotionIntent intent;
        float moveYaw, blocked, wind = 1, lastProgress = 1e9f, progressAt;
        boolean blockedSaid, hasMoveYaw;
        ActionStatus motion = ActionStatus.COMPLETED;
        // one timed action at a time: a blow or a reaction
        long actionId;
        MeleeSpec spec;
        int target;
        float t;
        MeleeSpec.Phase phase = MeleeSpec.Phase.RELEASE;
        ActionStatus actionStatus = ActionStatus.COMPLETED;
        boolean wasUp = true;
    }

    private final Raid r;
    private final Map<Long, Body> bodies = new HashMap<>();
    private final List<Listener> listeners = new ArrayList<>();
    private final ArrayList<Map.Entry<Long, Body>> walk = new ArrayList<>();
    private float dt = 1 / 60f;
    /** Counters (gates). */
    public int motions, sprints, blocks, contacts, hits, misses;

    public SydneyAdapter(Raid raid) { this.r = raid; }

    private Body body(long id) { return bodies.computeIfAbsent(id, k -> new Body()); }
    private Actor a(long id) { return r.actor((int) id); }
    private void emit(long id, long action, Event e) { for (Listener l : listeners) l.onSydneyEvent(id, action, e); }
    @Override public void addListener(Listener l) { listeners.add(l); }

    public void forget(long id) { bodies.remove(id); }

    /** Once a frame, before the minds run: the frame's length, and the progress of every blow and reaction under way. */
    public void frame(float frameDt) {
        dt = frameDt;
        // 0.8: over a copy. A blow that lands here can kill, and a death takes its body out of this map - which, walked
        // directly, ended the game with a ConcurrentModificationException whenever someone was beaten to death.
        walk.clear();
        walk.addAll(bodies.entrySet());
        for (Map.Entry<Long, Body> e : walk) {
            Body b = e.getValue();
            Actor a = a(e.getKey());
            if (a == null) continue;
            boolean up = !a.dead && a.vital == Vital.ACTIVE && a.ragdoll == null;
            if (b.wasUp && !up) { emit(e.getKey(), b.actionId, Event.FOOTING_LOST); if (b.phase != MeleeSpec.Phase.RELEASE) { b.phase = MeleeSpec.Phase.RELEASE; b.actionStatus = ActionStatus.INTERRUPTED; } b.motion = ActionStatus.INTERRUPTED; }
            b.wasUp = up;
            b.wind = Math.min(1, b.wind + frameDt / SPRINT_RECOVER * (a.sprinting ? 0 : 1));
            if (b.phase == MeleeSpec.Phase.RELEASE || !up) continue;
            // a hit taken during the wind-up loses the attack
            if (b.phase == MeleeSpec.Phase.WINDUP && r.time < a.staggerUntil) { b.phase = MeleeSpec.Phase.RELEASE; b.actionStatus = ActionStatus.INTERRUPTED; Blows.interrupted++; emit(e.getKey(), b.actionId, Event.ACTION_COMPLETED); continue; }
            b.t += frameDt;
            switch (b.phase) {
                case WINDUP -> { if (b.t >= b.spec.windup()) { b.phase = MeleeSpec.Phase.ACTIVE_WINDOW; b.t = 0; contacts++; emit(e.getKey(), b.actionId, Event.CONTACT_WINDOW_OPEN); resolve(a, b); } }
                case ACTIVE_WINDOW -> { if (b.t >= b.spec.activeWindow()) { b.phase = MeleeSpec.Phase.RECOVERY; b.t = 0; emit(e.getKey(), b.actionId, Event.CONTACT_WINDOW_CLOSED); } }
                case RECOVERY -> { if (b.t >= b.spec.recovery()) { b.phase = MeleeSpec.Phase.RELEASE; b.actionStatus = ActionStatus.COMPLETED; emit(e.getKey(), b.actionId, Event.ACTION_COMPLETED); } }
                default -> { }
            }
        }
    }

    /** The contact window has opened: the host's combat rules decide whether anything is hit. Nobody is moved to make it so. */
    private void resolve(Actor a, Body b) {
        Actor t = r.actor(b.target);
        if (t == null || t.dead || !canReachMelee(a.id, b.target, b.spec.maxRange())) { misses++; a.fireCooldown = Math.max(a.fireCooldown, 0.85f); return; }
        a.meleeMove = b.spec.id();
        Blows.land(r, a, t);
        hits++;
    }

    @Override public void setMotion(long actorId, MotionIntent in) {
        Actor a = a(actorId);
        if (a == null || a.dead) return;
        Body b = body(actorId);
        b.intent = in;
        motions++;
        if (a.vital != Vital.ACTIVE || a.ragdoll != null || a.seated) { b.motion = ActionStatus.INTERRUPTED; return; }
        Archetypes.Arch ar = Archetypes.arch(a.archetype);
        // ---- stance
        // (1.1: measured as the body is moved - on a flight of stairs a plain box found no room and everybody went up them prone)
        boolean crouchRoom = Physics.bodyFree(r.world, a.x, a.y, a.z, a.radius, a.stand * Actor.CROUCH_H), standRoom = Physics.bodyFree(r.world, a.x, a.y, a.z, a.radius, a.stand);
        a.prone = in.stance() == Stance.PRONE || !crouchRoom;
        a.crouch = !a.prone && (in.stance() == Stance.CROUCH || !standRoom);
        float dx = (float) in.destination().x() - a.x, dz = (float) in.destination().z() - a.z, d = (float) Math.sqrt(dx * dx + dz * dz);
        // 0.9: a destination on another floor is somewhere to climb to, not somewhere to stand under
        float dy = (float) in.destination().y() - a.y;
        a.goalY = Math.abs(dy) > 1.6f ? (float) in.destination().y() : Float.NaN; a.goalYAt = r.time;   // (good for this frame only: whatever else moves this body says where for itself)
        boolean stop = in.gait() == Locomotion.STOP || d < 0.45f && Float.isNaN(a.goalY);
        // a blow in progress roots the feet
        if (b.phase == MeleeSpec.Phase.WINDUP || b.phase == MeleeSpec.Phase.ACTIVE_WINDOW) stop = true;
        float faceYaw = Float.NaN;
        if (in.facingTarget() != null) { float fx = (float) in.facingTarget().x() - a.x, fz = (float) in.facingTarget().z() - a.z; if (fx * fx + fz * fz > 0.04f) faceYaw = (float) Math.atan2(-fx, -fz); }
        a.sprinting = false;
        if (stop) {
            Steering.stop(a);
            a.path = null;
            b.motion = ActionStatus.COMPLETED;
            b.blocked = 0; b.blockedSaid = false; b.hasMoveYaw = false;
            if (!Float.isNaN(faceYaw)) a.yaw = Steering.turn(a.yaw, faceYaw, dt * 6);
            settleInCover(a, in, faceYaw);
            return;
        }
        a.coverAmt = 0; a.coverSide = 0; a.coverPeek = false;
        // ---- gait
        float speed = switch (in.gait()) { case WALK -> ar.speed() * 1.25f; case SPRINT -> Math.min(SPRINT_MAX, ar.runSpeed() * SPRINT_MUL); default -> ar.runSpeed() * 0.92f; };
        if (in.gait() == Locomotion.SPRINT) {
            // nobody sprints for ever, and nobody sprints crouched, hurt in the leg or along the ground
            if (b.wind <= 0.02f || a.crouch || a.prone || a.speedMul < 0.9f) speed = ar.runSpeed() * 0.92f;
            else { a.sprinting = true; b.wind = Math.max(0, b.wind - dt / SPRINT_SECONDS); if (b.wind <= 0.02f) sprints++; }
        }
        if (a.prone) speed = Math.min(speed, 1.05f); else if (a.crouch) speed = Math.min(speed, ar.speed() * 1.15f);
        if (r.night() && !a.light && !a.mate()) speed *= 0.9f;
        // ---- travel: the heading that carries the body is its own, kept apart from where the eyes and the weapon point
        if (!b.hasMoveYaw) { b.moveYaw = (float) Math.atan2(-dx, -dz); b.hasMoveYaw = true; }
        float look = a.yaw;
        a.yaw = b.moveYaw;
        Steering.goTo(r, a, (float) in.destination().x(), (float) in.destination().z(), speed, dt);
        b.moveYaw = a.yaw;
        // 1.0: nobody runs backwards. Eyes and weapon stay on the threat while the body moves only when it is walking, or when
        // the way it is going is not behind it: a run to cover that lies away from the threat is run facing the cover, and the
        // body comes round to the threat when it gets there. (It used to keep facing the threat at a full run - a man sprinting
        // for a wall backwards.) Backing off at a walk is slower than walking forward.
        float away = Float.isNaN(faceYaw) ? 0 : Math.abs(wrap(faceYaw - b.moveYaw));
        boolean fast = in.gait() != Locomotion.WALK && !a.crouch && !a.prone;
        if (!Float.isNaN(faceYaw) && in.aimWhileMoving() && !a.sprinting && !(fast && away > 1.75f)) {
            a.faceSet = true; a.faceYaw = b.moveYaw;
            a.yaw = Steering.turn(look, faceYaw, dt * 7);
            if (away > 1.75f) { a.vx *= 0.72f; a.vz *= 0.72f; }
        } else a.faceSet = false;
        // ---- progress, or the lack of it
        if (d < b.lastProgress - 0.25f) { b.lastProgress = d; b.progressAt = r.time; }
        if (b.lastProgress > 1e8f || d > b.lastProgress + 3) { b.lastProgress = d; b.progressAt = r.time; }
        boolean stalled = a.stuckTime > 1.1f || r.time - b.progressAt > 2.6f;
        if (stalled) {
            b.blocked += dt;
            b.motion = ActionStatus.BLOCKED;
            if (!b.blockedSaid) { b.blockedSaid = true; blocks++; emit(actorId, MOTION, Event.MOTION_BLOCKED); }
        } else { b.blocked = 0; b.blockedSaid = false; b.motion = ActionStatus.RUNNING; }
    }

    /**
     * Stopped at a cover point: the body goes side-on to the obstacle - a shoulder to it, the head turned to the
     * threat - or, with a weapon up and the stance standing behind low cover, half-rises to look over it.
     */
    private void settleInCover(Actor a, MotionIntent in, float faceYaw) {
        absentialis.world.CoverMap.Point p = a.cover;
        if (p == null || !p.valid || a.distXZ(p.cx(), p.cz()) > 1.6f) { a.coverAmt = 0; a.coverSide = 0; a.coverPeek = false; a.faceSet = false; return; }
        a.coverAmt = 1;
        boolean low = p.height == absentialis.world.CoverMap.LOW;
        boolean out = low ? in.stance() == Stance.STAND : a.distXZ(p.cx(), p.cz()) > 0.5f;
        a.coverPeek = low && out;
        if (out) { a.coverSide = 0; a.faceSet = false; return; }
        // hidden: side-on, whichever shoulder is nearer the way the body already faces
        float lx = p.leftX(), lz = p.leftZ();
        float yawA = (float) Math.atan2(-lx, -lz), yawB = (float) Math.atan2(lx, lz), base = a.faceSet ? a.faceYaw : a.yaw;
        boolean right = a.coverSide != 0 ? a.coverSide > 0 : Math.abs(wrap(yawA - base)) <= Math.abs(wrap(yawB - base));
        a.coverSide = right ? 1 : -1;
        if (!a.faceSet) { a.faceSet = true; a.faceYaw = a.yaw; }
        a.faceYaw = Steering.turn(a.faceYaw, right ? yawA : yawB, dt * 7);
        if (!Float.isNaN(faceYaw)) a.yaw = Steering.turn(a.yaw, faceYaw, dt * 6);
    }

    private static float wrap(float x) { while (x > Math.PI) x -= 2 * Math.PI; while (x < -Math.PI) x += 2 * Math.PI; return x; }

    /** A creature's intent: its body does the rest (see {@link Creatures}). A body under physics takes no intents. */
    @Override public void setCreature(long actorId, CreatureIntent in) {
        Actor a = a(actorId);
        if (a == null || a.dead) return;
        Body b = body(actorId);
        motions++;
        if (a.ragdoll != null || a.seated) { b.motion = ActionStatus.INTERRUPTED; return; }
        Creatures.drive(r, a, in, dt);
        boolean going = Math.abs(a.vx) + Math.abs(a.vz) > 0.25f;
        boolean stalled = a.stuckTime > 1.1f;
        if (stalled) {
            b.blocked += dt;
            b.motion = ActionStatus.BLOCKED;
            if (!b.blockedSaid) { b.blockedSaid = true; blocks++; emit(actorId, MOTION, Event.MOTION_BLOCKED); }
        } else { b.blocked = 0; b.blockedSaid = false; b.motion = going ? ActionStatus.RUNNING : ActionStatus.COMPLETED; }
    }

    @Override public void setAim(long actorId, AimIntent in) {
        Actor a = a(actorId);
        if (a == null || a.dead || in.worldTarget() == null) return;
        float fx = (float) in.worldTarget().x() - a.x, fz = (float) in.worldTarget().z() - a.z;
        if (fx * fx + fz * fz < 0.04f) return;
        // steadier aim comes round faster; the look height is what the renderer pitches the weapon by
        float aimYaw = (float) Math.atan2(-fx, -fz), rate = dt * (3.5f + 4.5f * (float) in.steadiness());
        // 1.3: nobody runs backwards. The aim used to turn the whole body after the legs had been pointed along the way it was
        // going - so a man running from a threat ran facing it, feet first. Moving faster than a walk, the body (and the
        // stride) keeps to the way it is going; the eyes and the weapon go round only as far as a torso twists (about 70
        // degrees). Backing off at a walk, facing the threat, is still allowed - that is what a walk away under a gun is.
        float vx = a.vx, vz = a.vz, v = (float) Math.sqrt(vx * vx + vz * vz);
        if (v > RUN_FACING && a.onGround && !a.climbing) {
            float travel = (float) Math.atan2(-vx, -vz);
            if (Math.abs(wrap(aimYaw - travel)) > 1.75f) {
                if (!a.faceSet) { a.faceSet = true; a.faceYaw = a.yaw; }
                a.faceYaw = Steering.turn(a.faceYaw, travel, dt * 9);
                float rel = Math.max(-TWIST, Math.min(TWIST, wrap(aimYaw - a.faceYaw)));
                a.yaw = Steering.turn(a.yaw, a.faceYaw + rel, rate);
                a.memX = (float) in.worldTarget().x(); a.memY = (float) in.worldTarget().y() - 1.2f; a.memZ = (float) in.worldTarget().z();
                return;
            }
        }
        a.yaw = Steering.turn(a.yaw, aimYaw, rate);
        a.memX = (float) in.worldTarget().x(); a.memY = (float) in.worldTarget().y() - 1.2f; a.memZ = (float) in.worldTarget().z();
    }

    @Override public void requestMelee(long actorId, long actionId, MeleeIntent in) {
        Actor a = a(actorId);
        Body b = body(actorId);
        if (a == null || a.dead || a.vital != Vital.ACTIVE || a.ragdoll != null) { b.actionId = actionId; b.actionStatus = ActionStatus.FAILED; return; }
        if (b.phase != MeleeSpec.Phase.RELEASE) { return; }                          // one blow at a time
        b.spec = switch (in.attackType()) { case "shove" -> MeleeSpec.SHOVE; case "grab" -> MeleeSpec.GRAB; default -> MeleeSpec.STRIKE; };
        b.actionId = actionId; b.target = (int) in.targetId(); b.t = 0;
        b.phase = MeleeSpec.Phase.WINDUP; b.actionStatus = ActionStatus.RUNNING;
        a.meleeWind = (float) b.spec.windup();
        if (a.anim != null) a.anim.play("melee", (float) (b.spec.windup() + 0.3));
    }

    @Override public void requestReaction(long actorId, long actionId, ReactionIntent in) {
        Actor a = a(actorId);
        if (a == null || a.dead) return;
        Body b = body(actorId);
        b.actionId = actionId;
        if ("dodge".equals(in.reactionType())) { a.vx += (float) in.impulse().x(); a.vz += (float) in.impulse().z(); a.pvx = a.vx; a.pvz = a.vz; b.actionStatus = ActionStatus.COMPLETED; emit(actorId, actionId, Event.DODGE_COMPLETED); return; }
        // 0.9: a reaction is the body's to have. With a push behind it, it is simulated; a clip only where the body cannot be
        float il = (float) Math.sqrt(in.impulse().x() * in.impulse().x() + in.impulse().z() * in.impulse().z());
        if (il > 0.2f && in.severity() > 0.35 && r.gore.ragdolls.unbalance(a, (float) in.impulse().x() / il, (float) in.impulse().z() / il, 8 + 16 * (float) in.severity(), "torso")) { b.actionStatus = ActionStatus.COMPLETED; return; }
        a.staggerUntil = Math.max(a.staggerUntil, r.time + 0.3f + 0.9f * (float) in.severity());
        if (a.anim != null) a.anim.play("stumble", 0.6f);
        b.actionStatus = ActionStatus.COMPLETED;
    }

    @Override public ActionStatus status(long actorId, long actionId) {
        Body b = bodies.get(actorId);
        if (b == null) return ActionStatus.COMPLETED;
        if (actionId == MOTION) return b.motion;
        return b.actionId == actionId ? b.actionStatus : ActionStatus.COMPLETED;
    }

    @Override public boolean canReachMelee(long attackerId, long targetId, double reach) {
        Actor a = a(attackerId), t = a(targetId);
        if (a == null || t == null || a.dead || t.dead) return false;
        if (Math.abs(a.y - t.y) > 1.3f || a.dist(t) > reach + a.radius + t.radius * 0.5f) return false;
        return Physics.los(r.world, a.x, a.eyeY(), a.z, t.x, t.y + t.height() * 0.6f, t.z);
    }

    @Override public void cancelAction(long actorId, long actionId) {
        Body b = bodies.get(actorId);
        if (b == null) return;
        if (actionId == MOTION) { b.intent = null; b.motion = ActionStatus.COMPLETED; return; }
        // a blow already in its window or recovery runs out: it cannot be taken back
        if (b.actionId == actionId && b.phase == MeleeSpec.Phase.WINDUP) { b.phase = MeleeSpec.Phase.RELEASE; b.actionStatus = ActionStatus.INTERRUPTED; Actor a = a(actorId); if (a != null) a.meleeWind = 0; }
    }

    /** How much sprint an actor has left, 0 .. 1 (overlay, gates). */
    public float wind(long id) { Body b = bodies.get(id); return b == null ? 1 : b.wind; }
}
